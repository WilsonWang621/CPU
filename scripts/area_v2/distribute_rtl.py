#!/usr/bin/env python3
"""Generate equivalent structural RTL with bounded logic-net fanout.

This is an HDL generation step, not a replacement for the course evaluator.
The output contains ordinary Boolean logic, positive-edge registers, and
preserved pairs of generic inverters. No library blackboxes or timing
exceptions are emitted. Run the unmodified make synth on the output.
"""
import argparse
from collections import defaultdict
from copy import deepcopy
import gc
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'scripts'))
from synth import quote, run_yosys
from toolchain import DEFAULT_APPIMAGE, enter_appimage, packaged_tool


def emit_rtl(path, top):
    """Pack independent scalar operations to keep evaluator elaboration small.

    In particular, emitting 40,000 individual always blocks needlessly makes
    the course elaborated JSON hundreds of MB. Groups share only syntax, not
    state, enables, or logic. Separate wire names also avoid false vector
    combinational loops in event-driven simulators.
    """
    groups = defaultdict(list)
    registers, nets = set(), set()
    drivers = {}
    for name, cell in top['cells'].items():
        if cell['type'] not in ('$_DFF_P_', '$_DFF_N_'):
            for port, bits in cell['connections'].items():
                if cell['port_directions'][port] == 'output':
                    for b in bits:
                        drivers[b] = name
    levels, visiting = {}, set()

    def level(name):
        if name in levels:
            return levels[name]
        if name in visiting:
            raise ValueError('combinational cycle at ' + name)
        cell = top['cells'][name]
        if cell['type'] in ('$_DFF_P_', '$_DFF_N_'):
            return 0
        visiting.add(name)
        inputs = [b for p, bits in cell['connections'].items()
                  if cell['port_directions'][p] == 'input' for b in bits]
        value = 1 + max((level(drivers[b]) if b in drivers else 0 for b in inputs), default=0)
        visiting.remove(name)
        levels[name] = value
        return value

    for name, cell in top['cells'].items():
        # Pack only peers in the combinational DAG. Mixing dependent bits in
        # one vector operator creates artificial vector cycles in HDL tools.
        groups[(cell['type'], level(name))].append((name, cell))
        for bits in cell['connections'].values():
            nets.update(b for b in bits if isinstance(b, int))
        if cell['type'] in ('$_DFF_P_', '$_DFF_N_'):
            registers.update(cell['connections']['Q'])
    for port in top['ports'].values():
        nets.update(b for b in port['bits'] if isinstance(b, int))

    def bit(value):
        return f'n{value}' if isinstance(value, int) else "1'b" + value

    def bus(bits):
        return '{' + ','.join(bit(b) for b in reversed(bits)) + '}'

    binary = {'$_AND_': '&', '$_OR_': '|', '$_XOR_': '^',
              '$_NAND_': '&', '$_NOR_': '|', '$_XNOR_': '^'}
    supported = {*binary, '$_NOT_', '$_MUX_', '$_DFF_P_', '$_DFF_N_', 'area_v2_timing_inv'}
    kinds = {kind for kind, _ in groups}
    if kinds - supported:
        raise ValueError('unsupported generic cells: ' + str(kinds - supported))
    with path.open('w') as output:
        output.write('// Generated by scripts/area_v2/distribute_rtl.py.\n')
        output.write('// Same-cycle structural implementation; all buffers are real synthesized logic.\n')
        output.write('module student_top(' + ','.join(top['ports']) + ');\n')
        for name, port in top['ports'].items():
            width = len(port['bits'])
            output.write(f'{port["direction"]} wire [{width-1}:0] {name};\n')
        for kind, bits in [('wire', nets - registers), ('reg', registers)]:
            ordered = sorted(bits)
            for start in range(0, len(ordered), 64):
                output.write(kind + ' ' + ','.join(bit(b) for b in ordered[start:start+64]) + ';\n')
        for name, port in top['ports'].items():
            left, right = (bus(port['bits']), name) if port['direction'] == 'input' else (name, bus(port['bits']))
            output.write(f'assign {left} = {right};\n')
        for (kind, _), entries in groups.items():
            if kind == 'area_v2_timing_inv':
                for name, cell in entries:
                    c = cell['connections']
                    output.write(f'(* keep = 1 *) area_v2_timing_inv {name}(.A({bit(c["A"][0])}),.Y({bit(c["Y"][0])}));\n')
                continue
            for start in range(0, len(entries), 64):
                cells = [c['connections'] for _, c in entries[start:start+64]]
                def port(p):
                    return bus([c[p][0] for c in cells])
                if kind in ('$_DFF_P_', '$_DFF_N_'):
                    clocks = {c['C'][0] for c in cells}
                    if len(clocks) != 1:
                        raise ValueError('register packing requires one clock')
                    edge = 'posedge' if kind == '$_DFF_P_' else 'negedge'
                    output.write(f'always @({edge} {bit(next(iter(clocks)))}) {port("Q")} <= {port("D")};\n')
                    continue
                if kind in binary:
                    expr = f'({port("A")} {binary[kind]} {port("B")})'
                    if kind in ('$_NAND_', '$_NOR_', '$_XNOR_'):
                        expr = '~' + expr
                elif kind == '$_NOT_':
                    expr = '~' + port('A')
                else:
                    expr = f'(({port("A")} & ~{port("S")}) | ({port("B")} & {port("S")}))'
                output.write(f'assign {port("Y")} = {expr};\n')
        output.write('endmodule\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=ROOT / 'build/distributed')
    parser.add_argument('--fanout', type=int, default=8)
    parser.add_argument('--reuse', action='store_true')
    parser.add_argument('--install', action='store_true',
                        help='also write the generated implementation and manifest under verilog/')
    args = parser.parse_args()
    if args.fanout < 2:
        parser.error('fanout must be at least two')
    enter_appimage(DEFAULT_APPIMAGE)
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    sources = [ROOT / 'verilog' / name for name in
               ('area_v2_core.v', 'pararisc_axi_adapter.sv', 'student_top.sv')]
    hashes = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sources}
    if args.reuse:
        if json.loads((out / 'source-hashes.json').read_text()) != hashes:
            raise ValueError('cannot reuse generic netlist after source changes')
    else:
        run_yosys(packaged_tool('yosys'), out, 'generic', [
            *['read_verilog -sv -D SYNTHESIS ' + quote(p) for p in sources],
            'hierarchy -check -top student_top',
            'synth -top student_top -flatten -noabc',
            'dffunmap',
            'check -assert',
            'write_json ' + quote(out / 'generic.json'),
        ])
        (out / 'source-hashes.json').write_text(json.dumps(hashes, indent=2) + '\n')
    design = json.loads((out / 'generic.json').read_text())
    top = design['modules']['student_top']
    cells = top['cells']
    for name in list(cells):
        if cells[name]['type'] == '$scopeinfo':
            del cells[name]
    original = deepcopy(cells)
    ports = deepcopy(top['ports'])
    clocks = set(ports['clock']['bits'])
    uses = defaultdict(list)
    high = max(b for net in top['netnames'].values() for b in net['bits'] if isinstance(b, int))
    for name, cell in cells.items():
        cell['attributes'] = {}
        for port, bits in cell['connections'].items():
            if cell['port_directions'][port] == 'input':
                for index, bit in enumerate(bits):
                    if isinstance(bit, int) and bit not in clocks:
                        uses[bit].append((name, port, index))
    for net in top['netnames'].values():
        if 'init' in net.get('attributes', {}):
            raise ValueError('initial state is unsupported; use explicit reset logic')
        net['attributes'] = {}
    inserted = []

    def buffer(bit, loads):
        nonlocal high
        high += 2
        middle, output = high - 1, high
        stem = f'distribute_{len(inserted)}'
        for suffix, a, y in [('n', bit, middle), ('p', middle, output)]:
            name = stem + suffix
            if name in cells:
                raise ValueError('generated name collision')
            cells[name] = {'hide_name': 0, 'type': 'area_v2_timing_inv', 'parameters': {},
                           'attributes': {'keep': '1'},
                           'port_directions': {'A': 'input', 'Y': 'output'},
                           'connections': {'A': [a], 'Y': [y]}}
            top['netnames'][name + '_wire'] = {'hide_name': 0, 'bits': [y], 'attributes': {}}
        inserted.append(stem)
        for name, port, index in loads:
            cells[name]['connections'][port][index] = output
        return stem + 'n', 'A', 0

    for bit, loads in list(uses.items()):
        while len(loads) > args.fanout:
            loads = [buffer(bit, loads[start:start + args.fanout])
                     for start in range(0, len(loads), args.fanout)]

    # Each inserted pair implements Y=~(~A). Contract the ACTUAL rewritten
    # graph, including higher tree levels, and check every original cell pin.
    parents = {}
    for stem in inserted:
        a = cells[stem + 'n']['connections']['A'][0]
        n = cells[stem + 'n']['connections']['Y'][0]
        assert cells[stem + 'p']['connections']['A'] == [n]
        parents[cells[stem + 'p']['connections']['Y'][0]] = a

    def contract(bit):
        visited = set()
        while bit in parents:
            if bit in visited:
                raise ValueError('buffer cycle')
            visited.add(bit)
            bit = parents[bit]
        return bit

    checked = 0
    for name, cell in original.items():
        for port, bits in cell['connections'].items():
            assert [contract(b) for b in cells[name]['connections'][port]] == bits, (name, port)
            checked += len(bits)
    assert top['ports'] == ports
    final_uses = defaultdict(int)
    for cell in cells.values():
        for port, bits in cell['connections'].items():
            if cell['port_directions'][port] == 'input':
                for bit in bits:
                    if isinstance(bit, int) and bit not in clocks:
                        final_uses[bit] += 1
    assert max(final_uses.values()) <= args.fanout
    emit_rtl(out / 'student_top.v', top)
    record = {'source_sha256': hashes, 'fanout_limit': args.fanout,
              'original_max_fanout': max(map(len, uses.values())),
              'final_max_fanout': max(final_uses.values()),
              'inverter_pairs': len(inserted), 'original_pins_checked': checked,
              'connectivity_contraction': 'pass', 'clock_and_ports_unchanged': True,
              'yosys_version': subprocess.check_output([packaged_tool('yosys'), '-V'], text=True).strip(),
              'generator_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              'inverter_rtl_sha256': hashlib.sha256((ROOT / 'verilog/area_v2_fanout.v').read_bytes()).hexdigest()}
    # Release the large graph before starting a second Yosys process.
    del design, top, cells, original, uses, final_uses, parents, inserted
    gc.collect()
    (out / 'filelist.f').write_text('student_top.v\n' + str(ROOT / 'verilog/area_v2_fanout.v') + '\n')
    record['generated_sha256'] = hashlib.sha256((out / 'student_top.v').read_bytes()).hexdigest()
    (out / 'distribution.json').write_text(json.dumps(record, indent=2) + '\n')
    if args.install:
        (ROOT / 'verilog/area_v2_structural.v').write_bytes((out / 'student_top.v').read_bytes())
        (ROOT / 'verilog/area_v2_structural.json').write_text(json.dumps(record, indent=2) + '\n')
    print(json.dumps(record, indent=2), flush=True)


if __name__ == '__main__':
    main()
